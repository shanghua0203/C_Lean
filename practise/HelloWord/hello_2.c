#include <stdio.h>
//  std : standard 
//  i : input
//  o : output
//  stdio.h : standard input output header file 標準輸入輸出

int main(){
    printf("%s\n", "Hello World!"); //%s: string
    printf("%c\n", 'X'); //%c: character
    printf("%f\n", 0.34); //%f: float
    printf("%d\n", 34); //%d: integer
    return 0;
}
